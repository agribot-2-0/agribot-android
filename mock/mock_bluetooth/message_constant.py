from enum import Enum


class CanMessageBytes(Enum):
    START_OF_FRAME_BYTE = 0x43
    COMMAND_BYTE = 0x00
    END_OF_FRAME_BYTE = 0x0D


class MessageCommand(Enum):
    HEARTBEAT = 0x01
    MOBILE_APP_HANDSHAKE = 0x0A
    AGRIBOT_HANDSHAKE = 0x0B
    MANUAL_MODE_INITIALIZATION_MESSAGE = 20
    MANUAL_MODE_RUN_MESSAGE = 21
    AUTO_START = 30
    AGRIBOT_ERROR = 200
    START_ENGINE = 90
    STOP_SIGNAL = 255
    MOVE_FORWARD_BACKWARD = 50
    ROTATE_CARRIAGES = 51
    RIDE_THE_CURVE = 53
    AGRIBOT_SET_SWITCH = 60
    AGRIBOT_DIAGNOSTIC_DATA_1 = 0x064
    AGRIBOT_HYDRAULICS_DATA = 0x069
    RFID_TAG = 151


class MessageArrayPosition(Enum):
    START_OF_FRAME_POSITION = 0
    LENGTH_POSITION = 1
    COMMAND_BYTE_POSITION = 2
    FIRST_BYTE_OF_ADDRESS_POSITION = 3
    SECOND_BYTE_OF_ADDRESS_POSITION = 4


class FrameConstant(Enum):
    EMPTY_ARRAY = 0
    BIT_SHIFT = 8
    ADDRESS_FLAG = 256
    BUFFER_SIZE = 1024


class MessageDirection(Enum):
    SERVER = "[TO_MOBILE_APP]"
    CLIENT = "[FROM_MOBILE_APP]"
